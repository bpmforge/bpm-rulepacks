#!/usr/bin/env node
// Regenerates the scorecard from the COMMITTED corpus/baselines/*.json +
// current pack/astgrep rule counts. Never runs the engines and never
// mutates a baseline — it only reads what score-corpus.mjs already wrote.
// Idempotent: re-running with no baseline changes produces byte-identical
// output.
//
// Two tables:
//   - per-corpus P/R/F1 (straight from each baseline)
//   - per-pack rule count + aggregate TP/FP/precision (summed across all
//     baselines' `perRule`). Recall/F1 are marked n/a per pack: the scorer
//     only attributes FN at the corpus level (labels aren't tagged with
//     which rule "should" have caught them), so per-pack recall isn't
//     derivable from what's committed — reported honestly rather than
//     fabricated.
//
// Usage:
//   node scripts/scorecard.mjs            # rewrite docs/CORPUS.md's scorecard section
//   node scripts/scorecard.mjs --stdout   # print the block only, don't touch docs/CORPUS.md
//   node scripts/scorecard.mjs --check    # exit 1 if docs/CORPUS.md is stale vs baselines
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, extname } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const args = process.argv.slice(2);
const stdoutOnly = args.includes('--stdout');
const check = args.includes('--check');

const baselineDir = join(ROOT, 'corpus', 'baselines');
const docsPath = join(ROOT, 'docs', 'CORPUS.md');
const START = '<!-- SCORECARD:START (generated by scripts/scorecard.mjs — do not hand-edit) -->';
const END = '<!-- SCORECARD:END -->';

// Known pack names (packs/<name>/ and astgrep/<name>/). Rule ids embed the
// pack as either a dotted SARIF path ("packs.owasp.bpm-owasp-..." /
// "astgrep.slop.bpm-slop-...") or a bare ast-grep id ("bpm-secret-...").
// "secret" (singular, in rule ids) maps to the "secrets" pack dir.
const PACKS = ['owasp', 'framework', 'slop', 'secrets'];
function packOf(ruleId) {
  const dotted = ruleId.match(/^(?:packs|astgrep)\.([a-z]+)\./);
  const bare = ruleId.match(/^bpm-([a-z]+)-/);
  const token = dotted?.[1] || bare?.[1];
  if (!token) return 'other';
  if (PACKS.includes(token)) return token;
  if (PACKS.includes(`${token}s`)) return `${token}s`;
  return token;
}

function countRuleIdsInDir(dir) {
  let n = 0;
  const walk = (d) => {
    if (!existsSync(d)) return;
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (['.yaml', '.yml'].includes(extname(e.name))) {
        n += (readFileSync(p, 'utf8').match(/^\s*-?\s*id:\s*\S+/gm) || []).length;
      }
    }
  };
  walk(dir);
  return n;
}

const packRuleCounts = {};
for (const pack of PACKS) {
  packRuleCounts[pack] = countRuleIdsInDir(join(ROOT, 'packs', pack)) + countRuleIdsInDir(join(ROOT, 'astgrep', pack));
}
const totalRules = Object.values(packRuleCounts).reduce((a, b) => a + b, 0);

const names = existsSync(baselineDir)
  ? readdirSync(baselineDir).filter((f) => f.endsWith('.json')).map((f) => f.replace(/\.json$/, '')).sort()
  : [];
const rows = names.map((name) => ({ name, ...JSON.parse(readFileSync(join(baselineDir, `${name}.json`), 'utf8')) }));

// Aggregate perRule TP/FP across every committed baseline, grouped by pack.
const packAgg = {};
for (const pack of PACKS) packAgg[pack] = { tp: 0, fp: 0 };
for (const r of rows) {
  for (const [ruleId, stats] of Object.entries(r.perRule || {})) {
    const pack = packOf(ruleId);
    packAgg[pack] ??= { tp: 0, fp: 0 };
    packAgg[pack].tp += stats.tp || 0;
    packAgg[pack].fp += stats.fp || 0;
  }
}

function fmt(x) { return x == null ? 'n/a' : x.toFixed(3); }
function precisionOf(tp, fp) { return tp + fp === 0 ? null : tp / (tp + fp); }

const lines = [
  START,
  '',
  '_Generated by `node scripts/scorecard.mjs` from `corpus/baselines/*.json` — rerun after any `--update-baseline` and commit both together._',
  '',
  `Rule corpus: **${totalRules}** rules across ${PACKS.length} packs (opengrep \`packs/\` + ast-grep \`astgrep/\` combined per pack).`,
  '',
  '### By corpus',
  '',
  '| Corpus | TP | FP | FN | Precision | Recall | F1 |',
  '|---|---|---|---|---|---|---|',
  ...(rows.length
    ? rows.map((r) => `| ${r.name} | ${r.tp} | ${r.fp} | ${r.fn} | ${fmt(r.precision)} | ${fmt(r.recall)} | ${fmt(r.f1)} |`)
    : ['| _(no baselines committed yet)_ | | | | | | |']),
  '',
  '### By pack',
  '',
  '_Recall/F1 are n/a per pack: the scorer attributes false negatives at the corpus level only (labels aren\'t tagged with which rule should have caught them), so per-pack recall isn\'t derivable from the committed baselines without changing what they store._',
  '',
  '| Pack | Rules | TP (all corpora) | FP (all corpora) | Precision |',
  '|---|---|---|---|---|',
  ...PACKS.map((p) => `| ${p} | ${packRuleCounts[p]} | ${packAgg[p].tp} | ${packAgg[p].fp} | ${fmt(precisionOf(packAgg[p].tp, packAgg[p].fp))} |`),
  '',
  END,
];
const block = lines.join('\n');

if (stdoutOnly || check) console.log(block);

if (!existsSync(docsPath)) { console.error(`docs/CORPUS.md not found at ${docsPath}`); process.exit(2); }

const doc = readFileSync(docsPath, 'utf8');
const re = new RegExp(`${escapeRe(START)}[\\s\\S]*?${escapeRe(END)}`);
const next = re.test(doc) ? doc.replace(re, block) : `${doc.trimEnd()}\n\n## Scorecard\n\n${block}\n`;

if (check) process.exit(next === doc ? 0 : 1);

if (!stdoutOnly) {
  writeFileSync(docsPath, next);
  console.log(`docs/CORPUS.md scorecard section refreshed (${rows.length} corpora, ${totalRules} rules across ${PACKS.length} packs).`);
}

function escapeRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }
